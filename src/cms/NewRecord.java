    private void saveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBtnActionPerformed
        // TODO add your handling code here:
        String appointmentID = (String) appointmentIDComboBox.getSelectedItem();
        String notes = notesTA.getText().trim();
        String recommendations = recommendationsTA.getText().trim();

        if (appointmentID == null || notes.isEmpty() || recommendations.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select an appointment and enter session notes with your recommendations.");
            return;
        }

        counselor.addConsultationNote(appointmentID, notes, recommendations, fileManager);
        
        if (parentDashboard != null) {
            parentDashboard.loadCounselorData();
        }
        
        javax.swing.JOptionPane.showMessageDialog(this, "Consultation record saved!");
        this.dispose();
    }//GEN-LAST:event_saveBtnActionPerformed

