    private void loadAppointmentOptions() {
        java.util.ArrayList<Appointment> myAppointments = counselor.viewMyAppointments(fileManager);
        javax.swing.DefaultComboBoxModel<String> model = new javax.swing.DefaultComboBoxModel<>();
        for (Appointment a : myAppointments) {
            if (a.getStatus().equalsIgnoreCase("Confirmed")){
                model.addElement(a.getAppointmentID());
            }
        }
        appointmentIDComboBox.setModel(model);
    }

