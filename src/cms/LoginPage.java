    private void SignInBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SignInBtnActionPerformed
        // TODO add your handling code here:\
        String username = usernameTf.getText().trim();
        String password = new String(passwordField.getPassword());

        // All the checking happens inside FileManager - the form just asks for the result
        User loggedInUser = FileManager.getLoggedInUser(username, password);

        if (loggedInUser == null) {
            JOptionPane.showMessageDialog(this, "Invalid username or password.");
            return;
        }

        FileManager fileManager = new FileManager();

        // Open the correct dashboard based on the user's actual class.
        // POLYMORPHISM: instanceof determines which subclass this really is.
        if (loggedInUser instanceof Admin) {
            this.dispose();
            new AdminGUI((Admin) loggedInUser, fileManager).setVisible(true);
        } else if (loggedInUser instanceof Counselor) {
            this.dispose();
            new CounselorDashboard((Counselor) loggedInUser, fileManager).setVisible(true);
        } else if (loggedInUser instanceof Student) {
            this.dispose();
            new StudentMenu((Student) loggedInUser, fileManager).setVisible(true);
        } else if (loggedInUser instanceof Receptionist) {
            this.dispose();
            new ReceptionistDashboard((Receptionist) loggedInUser, fileManager).setVisible(true);
        }
    }//GEN-LAST:event_SignInBtnActionPerformed

